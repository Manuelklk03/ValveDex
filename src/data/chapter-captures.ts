function toImages(capture: ChapterCapture, name: string) {
  const { entryId, gameId, map, width, height, brightened } = capture;
  const original: MediaAsset = {
    src: `/images/entries/${entryId}-${gameId}.webp`,
    alt: `${name}, captura del juego`,
    width,
    height,
    source: steamSources[gameId],
    credit: `Captura propia del mapa ${map}${brightened ? " (brillo aumentado)" : ""}`,
    license: "Material del juego © Valve",
  };
  return { original };
}

// Pone la captura en la aparición del capítulo que corresponde
export function withChapterCaptures(entry: Entry): Entry {
  const matching = captures.filter((c) => c.entryId === entry.id);
  if (matching.length === 0) return entry;
  return {
    ...entry,
    appearances: entry.appearances.map((appearance) => {
      const capture = matching.find((c) => c.gameId === appearance.gameId);
      return capture
        ? { ...appearance, images: toImages(capture, entry.name) }
        : appearance;
    }),
  };
}
